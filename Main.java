    public static void click() {
        currentInput = input.nextLine();
        if (currentInput.isEmpty()) {
            balance.addAndGet(moneyPerClick);
            System.out.printf(Painter.formatClickMessage());
        } else if (currentInput.equals("C") || currentInput.equals("c") || currentInput.equals("controls") || currentInput.equals("Controls")) {
            displayMenu("ControlsMenu");
        } else if (currentInput.equals("B") || currentInput.equals("b") || currentInput.equals("show") || currentInput.equals("Show") || currentInput.equals("balance") || currentInput.equals("Balance")) {
            displayMenu("BalanceMenu");
        } else if (currentInput.equals("U") || currentInput.equals("u") || currentInput.equals("Upgrades") || currentInput.equals("upgrades")) {
            BuyUpgrades.mainUpgrades();
        } else if (currentInput.equals("S") || currentInput.equals("s") || currentInput.equals("Cosmetics") || currentInput.equals("cosmetics") || currentInput.equals("Cosmetic") || currentInput.equals("cosmetic")) {
            displayMenu("CosmeticsMenu");
        } else if (currentInput.equals("end") || currentInput.equals("End") || currentInput.equals("stop") || currentInput.equals("Stop") || currentInput.equals("finish") || currentInput.equals("Finish")) {
            System.exit(0);
        } else if ((currentInput.equals("P") || currentInput.equals("p") || currentInput.equals("Passive") || currentInput.equals("passive")) && unlockedGeneratorProductionUpgrades[0] > 0) {
            if (generatorToggled) {
                Generator.generatorInterrupt();
            } else {
                Generator.generatorResume();
            }
        } else if ((currentInput.equals("M") || currentInput.equals("m") || currentInput.equals("Messages") || currentInput.equals("messages")) && unlockedGeneratorProductionUpgrades[0] > 0) {
            generatorMessages.set(!generatorMessages.get());
        } else if (currentInput.equals("D") || currentInput.equals("d")) {
            balance.set(balance.get() + 10000);
        }
    }

    public static void displayMenu(String which) {
        if (which.equals("StartMenu")) {
            System.out.printf("=======================================\n");
            System.out.printf("=====||Java Console Clicker Game||=====\n");
            System.out.printf("====||Type 'ENTER' to earn money!||====\n");
            System.out.printf("=====||Type 'c' to see Controls!||=====\n");
            System.out.printf("=======================================\n");
        } else if (which.equals("BalanceMenu")) {
            System.out.printf("You have %d %s\n", balance.get(), currency.get());
        } else if (which.equals("ControlsMenu")) {
            System.out.printf("%s\n", topDownMenuFormatter);
            System.out.printf("==Controls==\n");
            System.out.printf("------------\n");
            System.out.printf("[ENTER] Get Money\n");
            System.out.printf("[C / Controls] Controls Menu\n");
            System.out.printf("[B / Show / Balance] Show Balance\n");
            System.out.printf("[U / Upgrades] Uprades Shop\n");
            System.out.printf("[S / Cosmetics] Cosmetic Shop\n");
            if (unlockedGeneratorProductionUpgrades[0] > 0) {
                System.out.printf("[P / Passive] Toggle Passive Income\n");
                System.out.printf("[M / Messages] Toggle Passive Income Messages\n");
            }
            System.out.printf("[End / Stop / Finish] End Game\n");
            System.out.printf("%s\n", topDownMenuFormatter);

        } else if (which.equals("UpgradesMenu")) {
            BuyUpgrades.mainUpgrades();
        } else if (which.equals("CosmeticsMenu")) {
            BuyCosmetics.mainCosmetics();
        }
    }

    public static void clickUpgrades(String what, int howMuch, String displayMessage) {
        if (what.equals("Unlock")) {
            unlockedClickPowerUpgrades[0] = 1;
            System.out.printf("You unlocked **Click Upgrades**!\n");
        } else if (what.equals("ClickPower")) {
            inBetween = String.valueOf(addToTotal[howMuch] * unlockedClickPowerUpgrades[howMuch]);
            moneyPerClick += addToTotal[howMuch];
            unlockedClickPowerUpgrades[howMuch]++;
            if (fancyMessages) {
                System.out.printf("%sYour **%s%s%s%s** was upgraded! %s%s%s%s%s -> %s%s%d!%s\n", LIME, BOLD, displayMessage, RESET, LIME, YELLOW, BOLD, inBetween, RESET, LIME, YELLOW, BOLD, addToTotal[howMuch] * unlockedClickPowerUpgrades[howMuch] / 100, RESET);
            } else {
                System.out.printf("Your **%s%s%s** was upgraded! %s%s%s -> %s%d!%s\n", BOLD, displayMessage, RESET,  BOLD, inBetween, RESET, BOLD, addToTotal[howMuch] * unlockedClickPowerUpgrades[howMuch] / 100, RESET);
            }

        }
    }

